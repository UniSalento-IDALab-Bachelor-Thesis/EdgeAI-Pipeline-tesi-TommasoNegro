# Creiamo una copia del dataframe per non sovrascrivere i dati originali
df_pipeline = df.copy()

print("--- INIZIO PIPELINE DI PRE-PROCESSING ---")
print(f"Dimensione iniziale del dataset: {len(df_pipeline)} campioni")

# 1. Gestione Valori Mancanti (Interpolazione lineare)
# Se il sensore si è spento per 15 minuti, calcoliamo il valore intermedio
df_pipeline = df_pipeline.interpolate(method='linear')

# 2. Rimozione Outlier (Metodo Statistico IQR)
# Calcoliamo il 1° e il 3° quartile sulla colonna del sensore gas
Q1 = df_pipeline['mq'].quantile(0.25)
Q3 = df_pipeline['mq'].quantile(0.75)
IQR = Q3 - Q1

# Definiamo i limiti fisiologici del segnale
lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

# Identifichiamo gli outlier (spike hardware) ed eliminiamo le relative righe
outliers = df_pipeline[(df_pipeline['mq'] < lower_bound) | (df_pipeline['mq'] > upper_bound)]
df_pipeline = df_pipeline[~df_pipeline.index.isin(outliers.index)].reset_index(drop=True)

print(f"Outlier rimossi: {len(outliers)} campioni")
print(f"Dimensione post-pulizia: {len(df_pipeline)} campioni")

