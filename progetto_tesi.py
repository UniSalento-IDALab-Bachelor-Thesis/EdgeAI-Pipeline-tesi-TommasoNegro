import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Input, LSTM, Dense, Dropout
import logging

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

print("--- INIZIO PIPELINE PREDITTIVA LSTM ---")

# ==========================================================================
# 0. VERIFICA DELLA COLONNA 'ts' E COSTRUZIONE DELL'INDICE TEMPORALE
# ==========================================================================
# La colonna 'ts' è in MINUTI trascorsi dall'inizio dell'acquisizione

unit_ts = 'm'

df_lstm = df_pipeline.copy()
diffs = df_lstm['ts'].diff().dropna()
print(f"Intervallo mediano tra campioni consecutivi (colonna 'ts'): {diffs.median()} minuti")
print(f"Intervallo minimo / massimo: {diffs.min()} / {diffs.max()} minuti")

df_lstm['datetime'] = pd.to_datetime(df_lstm['ts'], unit=unit_ts)
df_lstm = df_lstm.set_index('datetime').sort_index()

# ==========================================================================
# 1. DOWNSAMPLING A FINESTRE DI 15 MINUTI (aggregazione per media)
# ==========================================================================
df_resampled = df_lstm[['mq_ref']].resample('15min').mean().dropna()

print(f"\nCampioni originali (post-pulizia, Cap. 6.3): {len(df_lstm)}")
print(f"Campioni dopo il downsampling a 15 minuti: {len(df_resampled)}")

if len(df_resampled) < 50:
    print("\n*** ATTENZIONE: dopo il downsampling restano pochissimi campioni. ***")
    print("*** Verifica l'unità reale della colonna 'ts' (parametro unit_ts). ***")

# ==========================================================================
# 2. SCALING (MinMaxScaler, richiesto per le reti ricorrenti)
# ==========================================================================
scaler_lstm = MinMaxScaler(feature_range=(0, 1))
data_scaled = scaler_lstm.fit_transform(df_resampled[['mq_ref']].values)

# ==========================================================================
# 3. CREAZIONE DELLE FINESTRE TEMPORALI (Sliding Window)
# ==========================================================================
def create_sequences(data, time_steps=10):
    X, y = [], []
    for i in range(len(data) - time_steps):
        X.append(data[i:(i + time_steps), 0])
        y.append(data[i + time_steps, 0])
    return np.array(X), np.array(y)

time_steps = 10  # 10 campioni da 15 minuti = 150 minuti di storico
X_seq, y_seq = create_sequences(data_scaled, time_steps)

# Reshape per compatibilità tensoriale LSTM: [samples, time_steps, features]
X_seq = np.reshape(X_seq, (X_seq.shape[0], X_seq.shape[1], 1))

# ==========================================================================
# 4. DATA SPLITTING (Train 80% - Test 20%), ordine cronologico preservato
# ==========================================================================
split_idx = int(len(X_seq) * 0.8)
X_train_lstm, X_test_lstm = X_seq[:split_idx], X_seq[split_idx:]
y_train_lstm, y_test_lstm = y_seq[:split_idx], y_seq[split_idx:]

print(f"\nSequenze di Addestramento: {X_train_lstm.shape[0]}")
print(f"Sequenze di Validazione: {X_test_lstm.shape[0]}")

# ==========================================================================
# 5. ARCHITETTURA DELLA RETE NEURALE LSTM
# ==========================================================================
logging.info("Costruzione dell'architettura LSTM...")
model = Sequential()
model.add(Input(shape=(time_steps, 1)))
model.add(LSTM(units=50, return_sequences=False))
model.add(Dropout(0.2))  # Prevenzione dell'overfitting
model.add(Dense(units=1))

model.compile(optimizer='adam', loss='mean_squared_error')

# ==========================================================================
# 6. ADDESTRAMENTO DEL MODELLO
# ==========================================================================
logging.info("Avvio addestramento (30 Epoche)...")
history = model.fit(X_train_lstm, y_train_lstm, epochs=30, batch_size=16,
                     validation_split=0.1, verbose=1)

# ==========================================================================
# 7. INFERENZA PREDITTIVA SUL TEST SET
# ==========================================================================
logging.info("Calcolo delle previsioni sul Test Set...")
predictions = model.predict(X_test_lstm)

# Riportiamo i dati alla scala originale (inversione del MinMaxScaler)
predictions_inverse = scaler_lstm.inverse_transform(predictions)
y_test_inverse = scaler_lstm.inverse_transform(y_test_lstm.reshape(-1, 1))

# ==========================================================================
# 8. VALUTAZIONE METROLOGICA DELLE PERFORMANCE (in scala originale)
# ==========================================================================
mae_lstm = mean_absolute_error(y_test_inverse, predictions_inverse)
rmse_lstm = np.sqrt(mean_squared_error(y_test_inverse, predictions_inverse))
r2_lstm = r2_score(y_test_inverse, predictions_inverse)

print("\n--- PERFORMANCE DEL MODELLO LSTM (TEST SET, scala originale) ---")
print(f"MAE (Errore Assoluto Medio): {mae_lstm:.2f}")
print(f"RMSE (Radice dell'Errore Quadratico Medio): {rmse_lstm:.2f}")
print(f"R^2 Score (Coefficiente di Determinazione): {r2_lstm:.4f}")

# ==========================================================================
# 9. RENDERING GRAFICO (Forecasting)
# ==========================================================================
plt.figure(figsize=(12, 6))

plt.plot(y_test_inverse, color='crimson', label='Dato Reale Calibrato (Target)', linewidth=1.5)
plt.plot(predictions_inverse, color='teal', label='Previsione LSTM (Forecasting)',
         linewidth=1.5, linestyle='--')

plt.title('Forecasting LSTM: Previsione dell\'andamento inquinante '
          f'(MAE={mae_lstm:.2f}, RMSE={rmse_lstm:.2f}, R²={r2_lstm:.3f})',
          fontsize=13, pad=15)
plt.xlabel('Finestre Temporali da 15 min (Test Set)', fontsize=11)
plt.ylabel('Concentrazione MQ135 Calibrata (Valori ADC)', fontsize=11)
plt.legend(fontsize=11)
plt.grid(True, linestyle='--', alpha=0.5)

plt.tight_layout()
output_filename = "lstm_forecasting_performance.png"
plt.savefig(output_filename, dpi=300)
logging.info(f"Rendering completato. Immagine salvata come: {output_filename}")
plt.show()

